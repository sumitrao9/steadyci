"""Shareable Markdown report and fix hints (activation loop)."""

from __future__ import annotations

from .engine import ScanResult
from .fix_hints import hints_for


def _badge(score: int) -> str:
    if score >= 90:
        return "A"
    if score >= 75:
        return "B"
    if score >= 60:
        return "C"
    return "D"


def to_markdown(result: ScanResult, title: str = "SteadyCI Actions Health Report") -> str:
    grade = _badge(result.score)
    lines = [
        f"# {title}",
        "",
        f"**Score:** {result.score}/100 ({grade})  ",
        f"**Workflows:** {len(result.workflows)}  ",
        f"**Findings:** {len(result.errors)} error, {len(result.warnings)} warn, {len(result.infos)} info",
        "",
    ]
    if not result.findings:
        lines += ["No issues found.", ""]
    else:
        lines += ["## Findings", "", "| Severity | Rule | Location | Message | Fix |", "|---|---|---|---|---|"]
        for f in result.findings:
            loc = f.location.replace("|", "\\|")
            msg = f.message.replace("|", "\\|")
            fix = (f.remediation or "").replace("|", "\\|")
            lines.append(f"| {f.severity} | `{f.rule_id}` | `{loc}` | {msg} | {fix} |")
    hints = hints_for(result.findings)
    if hints:
        lines += ["", "## Suggested fixes", ""]
        for h in hints:
            lines += [f"### {h.title}", "", "```yaml", h.snippet, "```", ""]
    lines += [
        "## Next steps",
        "1. Pin `uses:` references to full commit SHAs (SEC010).",
        "2. Set least-privilege `permissions:` (SEC001/002).",
        "3. Replace deprecated runners (REL001).",
        "4. Keep untrusted PR data out of shell interpolation (SEC011/004/005).",
        "",
        "_Generated by [SteadyCI](https://github.com/sumitrao9/steadyci). Evidence-labeled, local-first._",
    ]
    return "\n".join(lines)
